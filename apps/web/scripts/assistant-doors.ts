/**
 * Writes src/lib/assistant/door-loaders.ts: one lazy import per GET door of the catalog the assistant may ever
 * read for a person (src/lib/assistant/doors.ts `neverReadWhy` is null), so the data questions' runner calls
 * the door's own handler with the asking person's session (the data questions, 11 October 2026). The catalog
 * is the truth; this file only names where each door's route file is, the way tests/api-catalog.test.ts
 * finds it. tests/assistant-data.test.ts fails when the written file and the catalog disagree.
 *
 *   npx tsx --tsconfig scripts/tsconfig.json scripts/assistant-doors.ts            write it
 *   npx tsx --tsconfig scripts/tsconfig.json scripts/assistant-doors.ts --check    exit 1 when it is stale
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ENDPOINTS } from "../src/lib/api-catalog";
import { neverReadWhy } from "../src/lib/assistant/doors";

const ROOT = join(__dirname, "..");
const OUT = join(ROOT, "src", "lib", "assistant", "door-loaders.ts");

/** The doors the file must carry, sorted, each with its route module's import path. */
export function loaderDoors(): { path: string; module: string }[] {
  const seen = new Set<string>();
  const out: { path: string; module: string }[] = [];
  for (const e of ENDPOINTS) {
    if (e.method !== "GET" || neverReadWhy(e) || seen.has(e.path)) continue;
    seen.add(e.path);
    const dir = e.path.replace(/\{(\w+)\}/g, "[$1]");
    if (!existsSync(join(ROOT, "src", "app", dir, "route.ts"))) continue;
    out.push({ path: e.path, module: `@/app${dir}/route` });
  }
  return out.sort((a, b) => a.path.localeCompare(b.path));
}

export function loaderSource(): string {
  const doors = loaderDoors();
  return [
    "/**",
    " * GENERATED by scripts/assistant-doors.ts from the API catalog: do not edit by hand. One lazy import per GET door",
    " * the assistant may read for a person (src/lib/assistant/doors.ts), so the data questions' runner (router.ts) calls",
    " * the door's own handler with the asking person's session. Regenerate after adding a GET door:",
    " *   npx tsx --tsconfig scripts/tsconfig.json scripts/assistant-doors.ts",
    " */",
    "type Handler = (request: Request, context: { params: Promise<Record<string, string>> }) => Promise<Response>;",
    "",
    "export const DOOR_LOADERS: Record<string, () => Promise<{ GET?: unknown }>> = {",
    ...doors.map((d) => `  ${JSON.stringify(d.path)}: () => import(${JSON.stringify(d.module)}),`),
    "};",
    "",
    "export type DoorHandler = Handler;",
    "",
  ].join("\n");
}

if (require.main === module) {
  const next = loaderSource();
  const now = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (process.argv.includes("--check")) {
    if (now !== next) {
      console.error("src/lib/assistant/door-loaders.ts is stale: run npx tsx --tsconfig scripts/tsconfig.json scripts/assistant-doors.ts");
      process.exit(1);
    }
    console.log(`door-loaders.ts is current (${loaderDoors().length} doors)`);
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT} (${loaderDoors().length} doors)`);
  }
}
