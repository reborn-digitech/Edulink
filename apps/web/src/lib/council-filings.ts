export type CouncilBuilt = { document: FilingDocument; figures: Record<string, number>; marks?: Record<string, number> };

/** Each return as a document and its headline figures, from the rows as they stand: the one function the generator, the council doors and the data audit share. */
export async function councilDocument(schoolId: string, kind: CollegeFilingKind, year: number, departmentId: string | null): Promise<CouncilBuilt> {
  if (kind === "PCI_INSPECTION") return pciDocument(schoolId, year);
  if (kind === "BCI_RETURN") return bciDocument(schoolId, year);
  if (kind === "NCTE_RETURN") return ncteDocument(schoolId, year);
  if (kind === "NBA_SAR") {
    if (!departmentId) throw new RuleRefusal("councilFilings.refuseDepartment", 422, undefined, "departmentId");
    return nbaDocument(schoolId, departmentId, year);
  }
  throw new Error(`councilDocument: ${kind} is not a council's return`);
}

function frame(p: Awaited<ReturnType<typeof schoolProfile>>, kind: CollegeFilingKind, year: number, sections: FilingSection[], subtitleExtra = ""): FilingDocument {
  return { title: FILING_TITLE[kind as keyof typeof FILING_TITLE], subtitle: `${p.name}${subtitleExtra ? ` · ${subtitleExtra}` : ""} · ${yearLabel(year)}`, school: p.name, footer: `${p.name} · ${L.generatedFrom}`, sections: [{ heading: L.institution, rows: [...profileRows(p), [L.year, yearLabel(year)]] }, ...sections] };
}

async function pciDocument(schoolId: string, year: number): Promise<CouncilBuilt> {
  const p = await schoolProfile(schoolId);
  const scope = await streamProgrammes(schoolId, "PHARMACY");
  const [staff, programmes, rooms, practical] = await Promise.all([streamTeachers(schoolId, scope), studentsByProgramme(schoolId, scope.programmes), db.room.findMany({ where: { schoolId, kind: "LAB" }, orderBy: { name: "asc" }, select: { name: true, capacity: true } }), practicalRecordSummary(schoolId, year)]);
  const labNames = rooms.map((r) => r.name);
  const [assets, stock] = labNames.length
    ? await Promise.all([
        db.asset.findMany({ where: { schoolId, location: { in: labNames }, disposedAt: null, status: { not: "DISPOSED" } }, select: { location: true } }),
        db.inventoryStock.findMany({ where: { schoolId, location: { in: labNames }, quantity: { gt: 0 } }, select: { location: true } }),
      ])
    : [[], []];
  const equipment = assets.length;
  const figures = {
    programmes: programmes.length,
    intake: programmes.reduce((a, x) => a + x.intake, 0),
    enrolled: programmes.reduce((a, x) => a + x.enrolled, 0),
    faculty: staff.length,
    phd: staff.filter((t) => t.qualification === "PHD").length,
    labs: rooms.length,
    equipment,
    practicalRecords: practical.records,
    practicalSigned: practical.signed,
    practicalStudents: practical.students,
  };
  const sections: FilingSection[] = [
    { heading: L.cadreByQualification, table: cadreTable(staff) },
    { heading: L.faculty, table: teacherTable(staff) },
    programmeSection(programmes),
    { heading: L.labs, table: { head: [L.lab, L.seats, L.equipment, L.consumables], rows: rooms.map((r) => [r.name, r.capacity, assets.filter((a) => a.location === r.name).length, stock.filter((s) => s.location === r.name).length]), wide: 0 } },
    {
      heading: L.practicals,
      rows: [[L.practicalRecords, String(practical.records)], [L.practicalSigned, String(practical.signed)], [L.practicalStudents, String(practical.students)]],
      table: { head: [L.course, L.programmeName, L.practicalRecords, L.practicalSigned, L.practicalStudents], rows: practical.byCourse.map((c) => [c.courseCode, c.courseName, c.records, c.signed, c.students]), wide: 1 },
    },
  ];
  return { document: frame(p, "PCI_INSPECTION", year, sections), figures };
}

async function libraryHoldings(schoolId: string) {
  const [titles, copies] = await Promise.all([
    db.libraryTitle.findMany({ where: { schoolId }, select: { id: true, category: true } }),
    db.libraryCopy.findMany({ where: { schoolId, status: { notIn: ["LOST", "WITHDRAWN"] } }, select: { titleId: true } }),
  ]);
  const catOf = new Map(titles.map((t) => [t.id, t.category]));
  const cats = [...new Set(titles.map((t) => t.category))].sort();
  const rows = cats.map((c) => [c, titles.filter((t) => t.category === c).length, copies.filter((x) => catOf.get(x.titleId) === c).length]);
  return { titles: titles.length, volumes: copies.length, rows };
}

