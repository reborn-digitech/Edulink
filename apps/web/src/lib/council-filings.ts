/** The latest published run of every session whose result came out in the window (or ever, with no window). */
async function termRows(schoolId: string, studentIds: string[], window: { from: string; to: string } | null) {
  if (!studentIds.length) return new Map<string, { status: string; sgpa: number | null }[]>();
  const runs = await db.resultRun.findMany({
    where: { schoolId, status: "PUBLISHED", ...(window ? { publishedAt: { gte: new Date(`${window.from}T00:00:00Z`), lte: new Date(`${window.to}T23:59:59Z`) } } : {}) },
    orderBy: [{ sessionId: "asc" }, { number: "desc" }],
    select: { id: true, sessionId: true },
  });
  const latest = new Map<string, string>();
  for (const r of runs) if (!latest.has(r.sessionId)) latest.set(r.sessionId, r.id);
  const rows = latest.size ? await db.termResult.findMany({ where: { runId: { in: [...latest.values()] }, studentMembershipId: { in: studentIds } }, select: { studentMembershipId: true, status: true, sgpaHundredths: true } }) : [];
  const out = new Map<string, { status: string; sgpa: number | null }[]>();
  for (const r of rows) out.set(r.studentMembershipId, [...(out.get(r.studentMembershipId) ?? []), { status: r.status, sgpa: r.sgpaHundredths === null ? null : r.sgpaHundredths / 100 }]);
  return out;
}

/** API of the students of one entry year, from the year's published results. */
async function apiOf(schoolId: string, studentIds: string[], window: { from: string; to: string }) {
  const rows = await termRows(schoolId, studentIds, window);
  const gpas: number[] = [];
  for (const list of rows.values()) {
    const sg = list.map((r) => r.sgpa).filter((x): x is number => x !== null);
    if (list.every((r) => r.status === "PASS") && sg.length) gpas.push(sg.reduce((a, b) => a + b, 0) / sg.length);
  }
  return { appeared: rows.size, successful: gpas.length, api: academicPerformance(gpas, rows.size) };
}

/**
 * THE FILING'S OWN YEAR (S4B-1, 5 Oct 2026, as LIFECYCLE-8 did for the AQAR in
 * iqac-filings.ts). Every fact is read as it stood in the academic year the SAR
 * covers, never on the day it is built, so a SAR filed in May and rebuilt by the
 * data audit years later prints the same figures:
 *   - the students (S, the SFR's numerator) are the seats that had entered by
 *     that year (entryYear) and were on the roll during it — a student who left
 *     (graduated, transferred) counts in the years they studied and not after;
 *     a seat that is not ACTIVE and has no leaving date is not counted, as before;
 *   - the first years are that year's entrants not exited by its end;
 *   - the teachers (F) were on the staff during it (`teachers` with `during`);
 *   - results are those published by its end, offers those made by its end and
 *     not declined by then, programmes those not archived by then.
 * Before, S was every ACTIVE seat today — next year's entrants and every
 * graduate (nothing sets a seat COMPLETED; leaving sets the membership's leftAt)
 * — so a past SAR's students and SFR grew every year after it was filed.
 */
export async function nbaFacts(schoolId: string, departmentId: string, year: number) {
  const w = windowOf(year);
  const asOf = new Date(`${w.to}T23:59:59.999Z`);
  const yearStart = new Date(`${w.from}T00:00:00.000Z`);
  const department = await db.department.findFirst({ where: { id: departmentId, schoolId }, select: { id: true, code: true, name: true } });
  const eligible = await nbaDepartments(schoolId, asOf);
  if (!department || !eligible.some((d) => d.id === departmentId)) throw new RuleRefusal("councilFilings.refuseDepartment", 422, undefined, "departmentId");
  const { programmes: all } = await streamProgrammes(schoolId, "ENGINEERING", asOf);
  const programmes = all.filter((p) => p.departmentId === departmentId);
  const pids = programmes.map((p) => p.id);
  const seats = await db.studentProgramme.findMany({ where: { schoolId, programmeId: { in: pids }, entryYear: { lte: year } }, select: { studentMembershipId: true, programmeId: true, entryYear: true, status: true, student: { select: { leftAt: true } } } });
  const duration = new Map(programmes.map((p) => [p.id, p.durationYears]));
  const onRoll = (s: (typeof seats)[number]) => (s.student.leftAt ? s.student.leftAt >= yearStart : s.status === "ACTIVE");
  const S = seats.filter(onRoll).length;

  // 4.1 — first-year admissions this year against the sanctioned intake.
  const intake = programmes.reduce((a, p) => a + p.intake, 0);
  const admitted = seats.filter((s) => s.entryYear === year).length;
  const er = enrolmentMarks(admitted, intake);

  // 4.2 — the latest three batches whose stipulated period ended by this year.
  const ended = seats.filter((s) => s.entryYear + (duration.get(s.programmeId) ?? 0) - 1 <= year);
  const batchYears = [...new Set(ended.map((s) => s.entryYear))].sort((a, b) => b - a).slice(0, 3);
  const everRows = await termRows(schoolId, ended.filter((s) => batchYears.includes(s.entryYear)).map((s) => s.studentMembershipId), { from: "1970-01-01", to: w.to });
  const batches = batchYears.map((e) => {
    const cohort = ended.filter((s) => s.entryYear === e);
    const graduated = cohort.filter((s) => s.status === "COMPLETED");
    const clean = graduated.filter((s) => (everRows.get(s.studentMembershipId) ?? []).every((r) => r.status === "PASS"));
    return { entryYear: e, admitted: cohort.length, graduated: graduated.length, withoutBacklog: clean.length };
  });
  const s421 = successMarks(batches.map((b) => successIndex(b.withoutBacklog, b.admitted)), 25);
  const s422 = successMarks(batches.map((b) => successIndex(b.graduated, b.admitted)), 15);

  // 4.3, 4.4, 8.3 — the year's results of the third, second and first years.
  const cohortOf = (k: number) => seats.filter((s) => s.entryYear === year - (k - 1)).map((s) => s.studentMembershipId);
  const [y1, y2, y3] = await Promise.all([apiOf(schoolId, cohortOf(1), w), apiOf(schoolId, cohortOf(2), w), apiOf(schoolId, cohortOf(3), w)]);

  // 4.5 — the placement index of the batches graduating around this year.
  const pidSet = new Set(pids);
  const placement = await Promise.all(
    [year - 1, year, year + 1].map(async (b) => {
      const students = (await batchStudents(schoolId, b)).filter((s) => s.programmeId && pidSet.has(s.programmeId));
      const ids = students.map((s) => s.id);
      const [offers, profiles] = ids.length
        ? await Promise.all([db.offer.findMany({ where: { studentMembershipId: { in: ids }, createdAt: { lte: asOf }, OR: [{ declinedAt: null }, { declinedAt: { gt: asOf } }] }, select: { studentMembershipId: true } }), db.placementProfile.findMany({ where: { studentMembershipId: { in: ids } }, select: { studentMembershipId: true, higherStudies: true, entrepreneur: true } })])
        : [[], []];
      const placed = new Set(offers.map((o) => o.studentMembershipId));
      const prof = new Map(profiles.map((p) => [p.studentMembershipId, p]));
      let higher = 0;
      let entrepreneurs = 0;
      for (const id of ids) {
        if (placed.has(id)) continue;
        if (prof.get(id)?.higherStudies) higher += 1;
        else if (prof.get(id)?.entrepreneur) entrepreneurs += 1;
      }
      return { batchYear: b, finalYear: ids.length, placed: placed.size, higher, entrepreneurs, index: successIndex(placed.size + higher + entrepreneurs, ids.length) };
    }),
  );
  const pl = placementMarks(placement.map((x) => x.index));

  // 5.1–5.3 — the department's teachers (visiting faculty are not counted).
  const staff = (await teachers(schoolId, [departmentId], w)).filter((t) => t.appointment !== "VISITING");
  const F = staff.length;
  const professors = staff.filter((t) => t.designation === "PROFESSOR").length;
  const associates = staff.filter((t) => t.designation === "ASSOCIATE_PROFESSOR").length;
  const assistants = staff.filter((t) => t.designation === "ASSISTANT_PROFESSOR" || t.designation === "LECTURER").length;
  const phd = staff.filter((t) => t.qualification === "PHD").length;
  const masters = staff.filter((t) => t.qualification === "PG" || t.qualification === "MPHIL").length;
  const sfr = sfrMarks(S, F);
  const cadre = cadreMarks(S, professors, associates, assistants);
  const fq = qualificationMarks(S, phd, masters);

  // 8.1 — first-year students against the teachers of the first-year courses this year; attainment of every offering this year.
  const offerings = pids.length
    ? await db.courseOffering.findMany({ where: { schoolId, course: { scheme: { programmeId: { in: pids } } }, term: { startsOn: { gte: w.from, lte: w.to } } }, orderBy: [{ course: { semester: "asc" } }, { course: { code: "asc" } }], select: { id: true, facultyMembershipId: true, course: { select: { code: true, name: true, semester: true } } } })
    : [];
  const firstYearFaculty = new Set(offerings.filter((o) => o.course.semester <= 2 && o.facultyMembershipId).map((o) => o.facultyMembershipId!)).size;
  const firstYearStudents = seats.filter((s) => s.entryYear === year && (s.status !== "EXITED" || (s.student.leftAt !== null && s.student.leftAt > asOf))).length;
  const fysfr = firstYearSfrMarks(firstYearStudents, firstYearFaculty);
  const attainment = [];
  for (const o of offerings) {
    const a = await attainmentForOffering(o.id);
    const levels = a.cos.map((c) => c.level).filter((x): x is number => x !== null);
    attainment.push({ code: o.course.code, name: o.course.name, cos: a.cos.length, coLevel: levels.length ? round2(levels.reduce((x, y) => x + y, 0) / levels.length) : null, pos: a.pos.filter((x) => x.attainment !== null).map((x) => `${x.code} ${x.attainment}`).join("; ") });
  }

  // The figures the computed items read, and their marks through THE ONE function that puts them together
  // (council-rules.ts nbaMarks; 5 Oct 2026): the insights and the simulator call it on the same figures.
  const sarFigures: NbaFigures = {
    S,
    F,
    intake,
    admitted,
    successNoBacklog: meanIndex(batches.map((b) => successIndex(b.withoutBacklog, b.admitted))),
    successStipulated: meanIndex(batches.map((b) => successIndex(b.graduated, b.admitted))),
    apiFirst: y1.api,
    apiSecond: y2.api,
    apiThird: y3.api,
    placement: meanIndex(placement.map((x) => x.index)),
    professors,
    associates,
    assistants,
    phd,
    masters,
    firstYearStudents,
    firstYearFaculty,
  };
  const marks: Record<string, number> = nbaMarks(sarFigures);
  return { department, programmes, S, F, intake, admitted, er, batches, s421, s422, y1, y2, y3, placement, pl, professors, associates, assistants, phd, masters, sfr, cadre, fq, firstYearStudents, firstYearFaculty, fysfr, attainment, staff, marks, sarFigures };
}

const nv = (v: number | null) => (v === null ? L.notRecorded : v);

async function nbaDocument(schoolId: string, departmentId: string, year: number): Promise<CouncilBuilt> {
  const [p, f, sheet] = await Promise.all([schoolProfile(schoolId), nbaFacts(schoolId, departmentId, year), readWorksheet(schoolId, "NBA_SAR", year, departmentId)]);
  const scoreOf = (code: string, computed: boolean, max: number) => (computed ? (f.marks[code] ?? 0) : Math.min(max, sheet.items[code]?.score ?? 0));
  const computedTotal = round2(NBA_SAR_ITEMS.filter((i) => i.computed).reduce((a, i) => a + scoreOf(i.code, true, i.marks), 0));
  const selfTotal = round2(NBA_SAR_ITEMS.filter((i) => !i.computed).reduce((a, i) => a + scoreOf(i.code, false, i.marks), 0));
  const figures = {
    students: f.S,
    faculty: f.F,
    enrolmentRatio: f.er.ratio ?? 0,
    successNoBacklog: f.s421.mean ?? 0,
    successStipulated: f.s422.mean ?? 0,
    apiFirst: f.y1.api ?? 0,
    apiSecond: f.y2.api ?? 0,
    apiThird: f.y3.api ?? 0,
    placementIndex: f.pl.mean ?? 0,
    sfr: f.sfr.ratio ?? 0,
    cadreMarks: f.cadre,
    fq: f.fq.fq ?? 0,
    fysfr: f.fysfr.ratio ?? 0,
    offerings: f.attainment.length,
    computedMarks: computedTotal,
    selfMarks: selfTotal,
    totalMarks: round2(computedTotal + selfTotal),
  };
  const facts: [string, string][] = [
    [L.intake, String(f.intake)],
    [L.admitted, String(f.admitted)],
    [L.enrolmentRatio, String(nv(f.er.ratio))],
    [L.successNoBacklog, String(nv(f.s421.mean))],
    [L.successStipulated, String(nv(f.s422.mean))],
    [L.apiThird, String(nv(f.y3.api))],
    [L.apiSecond, String(nv(f.y2.api))],
    [L.apiFirst, String(nv(f.y1.api))],
    [L.placementIndex, String(nv(f.pl.mean))],
    [L.students, String(f.S)],
    [L.fullTimeTeachers, String(f.F)],
    [L.sfr, String(nv(f.sfr.ratio))],
    [L.required, String(round2(f.S / 20))],
    [L.fq, String(nv(f.fq.fq))],
    [L.fysfr, String(nv(f.fysfr.ratio))],
  ];
  const sections: FilingSection[] = [
    { heading: L.department, rows: [[L.department, `${f.department.code} ${f.department.name}`]], table: { head: [L.programmeCode, L.programmeName, L.level, L.duration, L.intake], rows: f.programmes.map((x) => [x.code, x.name, x.level, x.durationYears, x.intake]), wide: 1 } },
    { heading: L.criterionMarks, table: { head: [L.criterion, L.metric, L.maxMarks, L.computedMarks, L.selfMarks], rows: NBA_SAR_ITEMS.map((i) => [i.code, i.text, i.marks, i.computed ? scoreOf(i.code, true, i.marks) : "", i.computed ? "" : (sheet.items[i.code]?.score ?? L.awaitingDepartment)]), wide: 1 } },
    { heading: L.computedFrom, rows: facts },
    { heading: L.batch, table: { head: [L.batch, L.admitted, L.outgoing, L.passed], rows: f.batches.map((b) => [b.entryYear, b.admitted, b.graduated, b.withoutBacklog]) } },
    { heading: L.placement, table: { head: [L.batch, L.outgoing, L.placed, L.higher, L.placementIndex], rows: f.placement.map((x) => [x.batchYear, x.finalYear, x.placed, x.higher + x.entrepreneurs, x.index === null ? L.notRecorded : round2(x.index)]) } },
    { heading: L.attainment, table: { head: [L.course, L.programmeName, L.coCount, L.coLevel, L.poLevels], rows: f.attainment.map((a) => [a.code, a.name, a.cos, a.coLevel ?? L.notRecorded, a.pos || L.notRecorded]), wide: 4 } },
    { heading: L.facultyCadre, rows: [[L.required, String(round2(f.S / 20))], ["PROFESSOR", String(f.professors)], ["ASSOCIATE_PROFESSOR", String(f.associates)], ["ASSISTANT_PROFESSOR", String(f.assistants)], ["PHD", String(f.phd)], ["PG", String(f.masters)]], table: teacherTable(f.staff) },
    ...NBA_SAR_CRITERIA.map((c): FilingSection => ({
      heading: `${L.criterion} ${c.code}: ${c.text} (${c.marks})`,
      paragraphs: NBA_SAR_ITEMS.filter((i) => i.criterion === c.code && !i.computed).map((i) => `${i.code} ${i.text}: ${sheet.items[i.code]?.note || L.awaitingDepartment}`),
    })).filter((s) => (s.paragraphs ?? []).length > 0),
    { heading: L.note, paragraphs: [L.notAScoreNba] },
  ];
  return { document: frame(p, "NBA_SAR", year, sections, `${f.department.code} ${f.department.name}`), figures, marks: f.marks };
}

