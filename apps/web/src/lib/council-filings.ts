const DESK: readonly Role[] = ["IQAC", "ADMIN", "PRINCIPAL"];
const DESK_WRITE: readonly Role[] = ["IQAC", "ADMIN"];

/** The academic year a council door reads by default: the last one finished (the documents page's default). */
export function defaultFilingYear(now = new Date()): number {
  return (now.getUTCMonth() >= 5 ? now.getUTCFullYear() : now.getUTCFullYear() - 1) - 1;
}

/** The department an HOD heads; null for anyone else. */
async function headOf(desk: Desk): Promise<string | null> {
  if (desk.role !== "HOD") return null;
  return (await db.department.findFirst({ where: { schoolId: desk.schoolId, hodMembershipId: desk.membershipId }, select: { id: true } }))?.id ?? null;
}

/** The NBA department a caller works on: an HOD their own (403 for another's), the desk the one asked for or the first. */
export async function nbaDepartmentFor(desk: Desk, asked: string | null | undefined): Promise<{ id: string; code: string; name: string }> {
  const list = await nbaDepartments(desk.schoolId);
  if (desk.role === "HOD") {
    const own = await headOf(desk);
    if (asked && asked !== own) throw new AccessError("councilFilings.refuseNotYourDepartment");
    const mine = list.find((d) => d.id === own);
    if (!mine) throw new AccessError("councilFilings.refuseNotApplicable", "NOT_FOUND");
    return mine;
  }
  const found = asked ? list.find((d) => d.id === asked) : list[0];
  if (!found) throw new RuleRefusal("councilFilings.refuseDepartment", 422, undefined, "departmentId");
  return found;
}

const readersOf = (kind: CollegeFilingKind): readonly Role[] => (kind === "NBA_SAR" ? [...DESK, "HOD"] : DESK);
const writersOf = (kind: CollegeFilingKind): readonly Role[] => (kind === "NBA_SAR" ? ["IQAC", "HOD"] : DESK_WRITE);

/** GET /api/v1/iqac/council — what the documents page draws: every kind, applying or greyed with the streams that would bring it, and the councils not built. */
export async function councilOverview(ctx: ActiveContext): Promise<CouncilOverview> {
  const desk = await iqacActor(ctx, [...DESK, "HOD"]);
  const streams = await streamsOf(desk.schoolId);
  const applies = applicableFilings(streams);
  let departments = applies.includes("NBA_SAR") ? await nbaDepartments(desk.schoolId) : [];
  if (desk.role === "HOD") {
    const own = await headOf(desk);
    departments = departments.filter((d) => d.id === own);
  }
  return {
    streams,
    items: COLLEGE_FILING_KINDS.map((kind) => ({ kind, applies: applies.includes(kind), streams: streamsBringing(kind), body: FILING_BODY[kind] })),
    notBuilt: UNBUILT_COUNCIL_STREAMS.map((s) => ({ stream: s, councils: [...STREAM_PRESETS[s].regulators], items: [...STREAM_PRESETS[s].notBuilt], here: streams.includes(s) })),
    nbaDepartments: departments,
    canGenerate: DESK_WRITE.includes(desk.role),
  };
}

/** GET /api/v1/iqac/council/{pci|bci|ncte|nba}: the return's figures from the rows as they stand and its worksheet. */
export async function councilView(ctx: ActiveContext, kind: CollegeFilingKind, query: { year?: number; departmentId?: string }): Promise<CouncilView> {
  const desk = await iqacActor(ctx, readersOf(kind));
  await assertFilingApplies(desk.schoolId, kind);
  const year = query.year ?? defaultFilingYear();
  const dept = kind === "NBA_SAR" ? await nbaDepartmentFor(desk, query.departmentId) : null;
  const [built, sheet] = await Promise.all([councilDocument(desk.schoolId, kind, year, dept?.id ?? null), readWorksheet(desk.schoolId, kind, year, dept?.id ?? null)]);
  const specs = worksheetItems(kind);
  const items = specs.map((s) => {
    const a = sheet.items[s.code];
    return { code: s.code, marks: s.marks, computed: s.computed, score: s.computed ? (built.marks?.[s.code] ?? 0) : (a?.score ?? null), answer: a?.answer ?? null, note: a?.note ?? "" };
  });
  const total = kind === "NBA_SAR" ? { computed: built.figures.computedMarks ?? 0, self: built.figures.selfMarks ?? 0, max: NBA_SAR_ITEMS.reduce((x, i) => x + i.marks, 0) } : null;
  return {
    kind,
    year,
    departmentId: dept?.id ?? null,
    departmentName: dept?.name ?? null,
    departments: kind === "NBA_SAR" ? (desk.role === "HOD" ? [dept!] : await nbaDepartments(desk.schoolId)) : [],
    figures: built.figures,
    items,
    total,
    canEdit: specs.length > 0 && writersOf(kind).includes(desk.role),
    updatedAt: sheet.updatedAt?.toISOString() ?? null,
  };
}

/**
 * POST /api/v1/iqac/council/{bci|ncte|nba}: the items given replace those
 * codes' answers, the rest stand. The office and the IQAC answer a
 * checklist; the HOD (their own department) and the IQAC write the SAR's
 * qualitative criteria. An unknown code, a computed item, a mark above the
 * item's or an answer on a SAR item is refused (422) and nothing is written.
 */
export async function saveWorksheet(ctx: ActiveContext, kind: WorksheetKind, input: z.infer<typeof worksheetSaveSchema>): Promise<CouncilView> {
  const desk = await iqacActor(ctx, writersOf(kind));
  await assertFilingApplies(desk.schoolId, kind);
  const dept = kind === "NBA_SAR" ? await nbaDepartmentFor(desk, input.departmentId) : null;
  const specs = new Map(worksheetItems(kind).map((s) => [s.code, s]));
  for (const it of input.items) {
    const spec = specs.get(it.code);
    if (!spec) throw new RuleRefusal("councilFilings.refuseItem", 422, undefined, "items");
    if (spec.computed) throw new RuleRefusal("councilFilings.refuseComputed", 422, undefined, "items");
    if (kind === "NBA_SAR" && (it.answer !== null || (it.score !== null && it.score > (spec.marks ?? 0)))) throw new RuleRefusal("councilFilings.refuseScore", 422, undefined, "items");
    if (kind !== "NBA_SAR" && it.score !== null) throw new RuleRefusal("councilFilings.refuseItem", 422, undefined, "items");
  }
  const departmentId = dept?.id ?? "";
  const key = { schoolId: desk.schoolId, kind, year: input.year, departmentId };
  const before = await db.filingWorksheet.findUnique({ where: { schoolId_kind_year_departmentId: key }, select: { itemsJson: true } });
  const items = before ? cleanItems(before.itemsJson) : {};
  for (const it of input.items) items[it.code] = { answer: it.answer, score: it.score, note: it.note };
  const itemsJson = JSON.stringify(items);
  await db.filingWorksheet.upsert({ where: { schoolId_kind_year_departmentId: key }, create: { ...key, itemsJson, updatedByUserId: desk.userId }, update: { itemsJson, updatedByUserId: desk.userId } });
  await audit({ schoolId: desk.schoolId, actorUserId: desk.userId, action: "iqac.worksheet.save", targetType: "FilingWorksheet", targetId: `${kind}:${input.year}:${departmentId}`, meta: { kind, year: input.year, departmentId: departmentId || null, codes: input.items.map((i) => i.code) } });
  return councilView(ctx, kind, { year: input.year, departmentId: dept?.id });
}
