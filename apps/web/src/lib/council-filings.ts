function cleanItems(raw: string): Items {
  const v = readJson<Record<string, unknown>>(raw, {});
  const out: Items = {};
  for (const [code, x] of Object.entries(v ?? {})) {
    if (!x || typeof x !== "object") continue;
    const o = x as Record<string, unknown>;
    out[code] = {
      answer: o.answer === "YES" || o.answer === "NO" || o.answer === "NA" ? o.answer : null,
      score: typeof o.score === "number" && Number.isFinite(o.score) ? o.score : null,
      note: typeof o.note === "string" ? o.note : "",
    };
  }
  return out;
}

export async function readWorksheet(schoolId: string, kind: CollegeFilingKind, year: number, departmentId: string | null = null): Promise<{ items: Items; updatedAt: Date | null }> {
  const row = await db.filingWorksheet.findUnique({ where: { schoolId_kind_year_departmentId: { schoolId, kind, year, departmentId: departmentId ?? "" } }, select: { itemsJson: true, updatedAt: true } });
  return { items: row ? cleanItems(row.itemsJson) : {}, updatedAt: row?.updatedAt ?? null };
}

const answerText = (a: WorksheetAnswer | null) => (a === "YES" ? L.yes : a === "NO" ? L.no : a === "NA" ? L.notApplicable : L.notAnswered);

function checklistSection(kind: "BCI_RETURN" | "NCTE_RETURN", items: Items): { section: FilingSection; complied: number; total: number } {
  const text: Record<string, string> = kind === "BCI_RETURN" ? BCI_ITEM_TEXT : NCTE_ITEM_TEXT;
  const specs = worksheetItems(kind);
  const rows = specs.map((s) => [text[s.code] ?? s.code, answerText(items[s.code]?.answer ?? null), items[s.code]?.note ?? ""]);
  return { section: { heading: L.checklist, table: { head: [L.item, L.answer, L.note], rows, wide: 0 } }, complied: specs.filter((s) => items[s.code]?.answer === "YES").length, total: specs.length };
}

