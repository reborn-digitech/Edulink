/**
 * THE FILINGS BY STREAM AND THE COUNCILS' RETURNS (5 October 2026).
 *
 * THE GATE. A college files what its streams bring (`applicableFilings`,
 * packages/contracts v1/council-filings.ts): a law college has no AICTE
 * disclosure, an engineering college has NBA's SAR. Every door that makes,
 * shows or publishes a filing asks `assertFilingApplies` first and answers a
 * kind the college does not file with 404 and the sentence
 * `councilFilings.refuseNotApplicable` — the same answer as a thing that is
 * not here. Filings already made stay readable: a college that drops a
 * stream keeps what it filed.
 *
 * THE FOUR RETURNS, each cut from the live rows at the moment it is
 * generated, frozen in CollegeFiling with the SHA-256 of its JSON body, and
 * regenerated by the data audit's iqac-filing check exactly as the seven
 * before them (buildFiling in iqac-filings.ts calls `councilDocument` here):
 *
 *   PCI_INSPECTION (pharmacy) — the teaching staff of the pharmacy
 *     programmes by cadre and qualification, the students by programme and
 *     year of study, the laboratories (Room kind LAB) with the equipment the
 *     asset register places in each and the stock lines kept there, and the
 *     practical record (stream-summaries.ts `practicalRecordSummary`).
 *   BCI_RETURN (law) — the law teachers, the students, the library's
 *     holdings by category, the moot court exercises and the court, firm and
 *     legal-aid internships (`lawInternshipSummary`), and the office's
 *     answers to the BCI's compliance items.
 *   NCTE_RETURN (teacher education) — the teachers by subject (their
 *     department), the students, the practice-teaching schools, postings and
 *     observed lessons (`teachingPracticeSummary`), and the office's answers
 *     to NCTE's infrastructure items.
 *   NBA_SAR (one per engineering department and year) — the SAR's
 *     quantitative items computed from the rows by council-rules.ts (4.1,
 *     4.2.1, 4.2.2, 4.3, 4.4, 4.5, 5.1, 5.2, 5.3, 8.1, 8.3), the course and
 *     programme outcome attainment of every offering of the year
 *     (`attainmentForOffering`), the faculty cadre table, and the HOD's
 *     self-assessed qualitative criteria; signed off by the principal.
 *
 * WHICH PROGRAMMES ARE A STREAM'S: those whose `stream` says so, or — at a
 * college whose only stream it is — every programme (the rule
 * stream-summaries.ts uses for law). A department is the stream's when one
 * of those programmes is its.
 *
 * WHAT IS UNTESTED: every return against its council's portal or inspection
 * form; the councils' formats change by notice and the documents follow the
 * data each asks for, not an upload template.
 */

